"""Offline checks for endpoint completeness and deterministic Java generation."""
import importlib.util
import json
import re
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("sync_qq_sdk_catalog", ROOT / "scripts/sync_qq_sdk_catalog.py")
catalog = importlib.util.module_from_spec(spec)
spec.loader.exec_module(catalog)


class QQSdkCatalogTest(unittest.TestCase):
    def test_generated_java_exactly_matches_the_official_snapshot(self):
        snapshot = json.loads(catalog.SPEC.read_text(encoding="utf-8"))
        self.assertEqual(100, len(snapshot["endpoints"]))
        self.assertEqual(49, len(snapshot["events"]))
        for name, expected in catalog.render(snapshot).items():
            self.assertEqual(expected, (catalog.JAVA / name).read_text(encoding="utf-8"), name)
        self.assertEqual(catalog.coverage(snapshot), (ROOT / "API_COVERAGE.md").read_text(encoding="utf-8"))
        signatures = {(e["method"], e["path"]) for e in snapshot["endpoints"]}
        self.assertEqual(len(signatures), len(snapshot["endpoints"]))
        for endpoint in snapshot["endpoints"]:
            self.assertTrue(endpoint["documentation"].startswith("https://bot.q.qq.com/wiki/develop/api-v2/"))
            self.assertRegex(endpoint["sha256"], r"^[a-f0-9]{64}$")
        for signature in [("POST", "/v2/users/{user_openid}/stream_messages"),
                          ("GET", "/gateway/bot"), ("PUT", "/channels/{channel_id}/threads"),
                          ("PATCH", "/guilds/{guild_id}/mute"),
                          ("POST", "/v2/media-images/prepare"),
                          ("POST", "/v2/groups/join_approval_strategy/{strategy_id}/execute")]:
            self.assertIn(signature, signatures)

    def test_legacy_channel_declarations_are_included_without_example_ids(self):
        page = '<main class="page"><h1>频道消息</h1><p>POST /channels/{channel_id}/messages</p>'
        page += '<pre>POST /channels/12345/messages</pre><h2>MESSAGE_AUDIT_PASS</h2></main>'
        with patch.object(catalog, "fetch", return_value=page):
            endpoints, events = catalog.parse_page("/develop/api-v2/server-inter/channel/message/send.html")
        self.assertEqual([("POST", "/channels/{channel_id}/messages")], [(e["method"], e["path"]) for e in endpoints])
        self.assertEqual("MESSAGE_AUDIT_PASS", events[0]["name"])

    def test_autogenerated_tables_and_restricted_capabilities_are_preserved(self):
        page = '<main class="page"><h1>成员列表</h1><p>内邀</p><table><tr><td>HTTP URL</td><td>/v2/groups/{group_openid}/members</td></tr>'
        page += '<tr><td>HTTP Method</td><td>GET</td></tr></table></main>'
        with patch.object(catalog, "fetch", return_value=page):
            endpoints, _ = catalog.parse_page("/develop/api-v2/autogen/api/members.html")
        self.assertTrue(endpoints[0]["restricted"])
        self.assertEqual("GET", endpoints[0]["method"])

    def test_sdk_has_no_spring_or_application_runtime_dependency(self):
        for source in (ROOT / "src/main/java").rglob("*.java"):
            imports = re.findall(r"^import (.*);$", source.read_text(encoding="utf-8"), re.M)
            self.assertFalse(any("org.springframework" in i or "top.sshh.officialbot" in i for i in imports), str(source))
